export function getFacultyInfo(prodiName: string): FacultyInfo {
  if (!prodiName) {
    return {
      fakultas: 'Universitas Islam Indonesia',
      lokasi: 'Gedung Kuliah Umum (GKU) Prof. Dr. Sardjito, Kampus Terpadu UII (Layanan Pusat)'
    };
  }

  // Normalize helper to strip out spaces, punctuation and program tags
  const cleanString = (str: string) => {
    return str
      .toLowerCase()
      .replace(/\s*\((international program|ip|internasional|reguler)\)/gi, '')
      .replace(/[\/\s._-]/g, '')
      .trim();
  };

  const inputCleaned = cleanString(prodiName);

  // 1. Try exact or tag-cleaned match first
  let cleanKey = Object.keys(PRODI_TO_FACULTY_MAP).find(
    k => cleanString(k) === inputCleaned
  );

  // 2. Fallback to fuzzy prefix/contains match if still not found
  if (!cleanKey) {
    cleanKey = Object.keys(PRODI_TO_FACULTY_MAP).find(
      k => {
        const kCleaned = cleanString(k);
        return kCleaned.includes(inputCleaned) || inputCleaned.includes(kCleaned);
      }
    );
  }

  if (cleanKey && PRODI_TO_FACULTY_MAP[cleanKey]) {
    return PRODI_TO_FACULTY_MAP[cleanKey];
  }

  return {
    fakultas: 'Universitas Islam Indonesia',
    lokasi: 'Gedung Kuliah Umum (GKU) Prof. Dr. Sardjito, Kampus Terpadu UII (Layanan Pusat)'
  };
}
